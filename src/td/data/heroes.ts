/** 英雄等級經驗門檻（累積 XP），最高 10 級 */
export const HERO_XP_TABLE = [0, 400, 1000, 1800, 2900, 4300, 6000, 8000, 10500, 13500];
export const HERO_MAX_LEVEL = HERO_XP_TABLE.length;

export function heroLevelForXp(xp: number): number {
  let lv = 1;
  for (let i = 0; i < HERO_XP_TABLE.length; i++) if (xp >= HERO_XP_TABLE[i]) lv = i + 1;
  return lv;
}

/** 英雄室「訓練」：花寶石換經驗（每次給目前這一級所需經驗的 40%，約 3 次＝120 寶石升一級） */
export const TRAIN_PRICE = 40;
export function trainXp(xp: number): number {
  const lv = heroLevelForXp(xp);
  if (lv >= HERO_MAX_LEVEL) return 0;
  const span = HERO_XP_TABLE[lv] - HERO_XP_TABLE[lv - 1];
  return Math.ceil((span * 0.4) / 10) * 10;
}

