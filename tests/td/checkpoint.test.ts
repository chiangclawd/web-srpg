import { test } from 'node:test';
import assert from 'node:assert/strict';
import { HEROES } from '../../src/td/data/heroes';
import { TOWERS } from '../../src/td/data/towers';
import { getLevel } from '../../src/td/data/levels';
import { restore, snapshot } from '../../src/td/sim/checkpoint';
import { mkWorld, run } from './helpers';

test('a checkpoint restores towers (levels, branches, skills, rally), economy, wave and cooldowns', () => {
  const level = getLevel('l9')!;
  const w = mkWorld(level, { hero: { def: HEROES.elena, xp: 3000 } });
  w.gold = 99999;
  const archer = w.build(0, 'archer')!;
  w.upgrade(archer);
  w.upgrade(archer);
  w.chooseBranch(archer, 1);
  const sk = TOWERS.archer.branches[1].skills![0].id;
  w.buySkill(archer, sk);
  w.buySkill(archer, sk);
  const barracks = w.build(3, 'barracks')!;
  w.upgrade(barracks);
  w.setRally(barracks, barracks.x + 20, barracks.y + 50);
  w.callNextWave();
  run(w, 8);
  w.gold = 321;
  w.lives = 17;
  w.meteorCd = 12;
  w.hazards[0].cd = 9;
  archer.dmgDealt = 1234;
  const cp = snapshot(w, { levelId: 'l9', mode: 'campaign', difficulty: 'normal' }, w.waveIndex);
  const json = JSON.parse(JSON.stringify(cp));

  const w2 = mkWorld(level, { hero: { def: HEROES[json.heroId], xp: json.hero.xp } });
  restore(w2, json);
  assert.equal(w2.gold, 321);
  assert.equal(w2.lives, 17);
  assert.equal(w2.waveIndex, w.waveIndex);
  assert.equal(w2.waveState, 'waiting');
  assert.ok(w2.canCallWave(), 'the next wave waits for the player');
  assert.equal(w2.meteorCd, 12);
  assert.equal(w2.hazards[0].cd, 9);
  assert.equal(w2.towers.length, 2);
  const a2 = w2.spots[0].tower!;
  assert.equal(a2.level, 4);
  assert.equal(a2.def, TOWERS.archer.branches[1]);
  assert.equal(a2.skills[sk], 2);
  assert.equal(a2.dmgDealt, 1234);
  assert.equal(a2.buildUntil, 0, 'restored towers are ready at once');
  const b2 = w2.spots[3].tower!;
  assert.equal(b2.level, 2);
  assert.deepEqual([b2.rallyX, b2.rallyY], [barracks.rallyX, barracks.rallyY]);
  assert.equal(w2.hero!.hero!.level, w.hero!.hero!.level, 'hero keeps the experience earned before the checkpoint');
  assert.equal(w2.stats.kills, w.stats.kills);
});
